#!/usr/bin/env python3
"""
Publish each rocky viewer's own terrain primitives on the GIS seam.

The GIS tools ARE one shared module set — 51 modules under `viewer/gis/`, the
same 47-tool registry and the same draw bar on every world. What was NOT shared
is the SEAM those modules call into: `window.GeoIDViewer`. Measured live on
Mars, three names the shared modules use were simply absent:

    surfacePoint          vector-render, the drapes, anything that hugs terrain
    getEffectiveRelief    vector-render, geotiff-adapter
    elevationNormalized   vector-render

Every one of those is already COMPUTED inside each planet viewer — as
`measureSurfaceRadius`, `getEffectiveTerrainRelief` and
`sampleElevationNormalized`. They were just never published, so a shared module
loaded on a planet asked for them and got `undefined`.

So this does not re-derive the terrain rule in a shared module, which is the
"second implementation drifts" trap this tree has paid for repeatedly (the
polygon-area formula in ten files, the imitated label engine, the fan apex).
It exposes what each viewer already has, in that viewer's own frame.

`surfacePoint` passes an explicit `{ kind: "planet" }` context rather than
letting `measureSurfaceRadius` default to `getActiveMeasureContext()`: the
default would answer in a MOON's frame whenever a moon happens to be the active
measure target, and a caller asking for a point on the planet must get one.

The four gas giants are deliberately untouched: they have no elevation map and
no `getEffectiveTerrainRelief`, so there is nothing to publish and nothing that
hugs their terrain.

Run:  python3 GeoID_GIS/services/port-viewer-seam.py [--check]
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
WORLDS = ["mars", "mercury", "moon", "venus", "pluto"]

# The seam literal already lists this; the new entries go directly after it.
ANCHOR = "        sphericalPolygonAreaKm2,\n"

BLOCK = """        // ── Terrain seam, published for the shared GIS modules ──────────
        // These three are what vector-render and the raster adapters ask a
        // viewer for so their geometry can hug the ground. Each is this
        // viewer's OWN computation, exposed rather than re-derived: a second
        // copy of the radius rule is exactly how the polygon-area formula came
        // to be wrong in ten files.
        //
        // Generated by services/port-viewer-seam.py — do not hand-edit; edit
        // the generator and re-run it.
        surfacePoint: (lat, lon, lift = 0) => latLonToVector3(
          lat, lon, measureSurfaceRadius(lat, lon, lift, { kind: "planet" })),
        getEffectiveRelief: () => getEffectiveTerrainRelief(),
        elevationNormalized: (lat, lon) => (elevationSampler
          ? sampleElevationNormalized(elevationSampler, lat, lon) : 0),
"""

MARK = "Terrain seam, published for the shared GIS modules"


def target(world: str) -> Path:
    return ROOT / "planet_explorer" / world / "viewer" / f"{world}-viewer.js"


def apply(check: bool) -> int:
    stale = 0
    for world in WORLDS:
        path = target(world)
        src = path.read_text(encoding="utf-8")
        if ANCHOR not in src:
            print(f"  {world:<9} ANCHOR MISSING — seam literal changed shape")
            stale += 1
            continue
        # Idempotent: strip a previous block before writing the current one.
        if MARK in src:
            src = re.sub(
                r"[ ]*// ── Terrain seam.*?elevationNormalized: \(lat, lon\) => \(elevationSampler\n"
                r".*?: 0\),\n",
                "", src, flags=re.S)
        want = src.replace(ANCHOR, ANCHOR + BLOCK, 1)
        if check:
            current = path.read_text(encoding="utf-8")
            if current != want:
                print(f"  {world:<9} STALE")
                stale += 1
            else:
                print(f"  {world:<9} up to date")
        else:
            path.write_text(want, encoding="utf-8")
            print(f"  {world:<9} seam published")
    return stale


if __name__ == "__main__":
    check = "--check" in sys.argv
    bad = apply(check)
    if check:
        print("uniform" if not bad else f"{bad} viewer(s) stale")
    sys.exit(1 if bad else 0)
