    for folder, viewer, group, radius_const in BODIES:
        path = ROOT / "planet_explorer" / folder / "viewer" / viewer
        text = path.read_text(encoding="utf-8")
        if radius_const not in text:
            raise SystemExit(f"{folder}: {radius_const} not found")
        updated = apply(text, render(block, group, radius_const))
        # The seam the HUD's Done and Cancel need, and the announcement the
        # pipeline sync listens for.
        if SEAM_OLD in updated:
            updated = updated.replace(SEAM_OLD, SEAM_NEW, 1)
        elif "clearStudyArea()" not in updated:
            raise SystemExit(f"{folder}: setStudyAreaPolygon seam not recognised")
        updated, rewrote = rewrite(updated, folder)
        if updated == text:
            print(f"  {folder:8s} unchanged")
            continue
        if rewrote:
            print(f"  {folder:8s} + {', '.join(rewrote)}")
        stale.append(folder)
        if not check:
            path.write_text(updated, encoding="utf-8")
        print(f"  {folder:8s} {'STALE' if check else 'ported'}")
    for folder, viewer, display in GAS_BODIES:
        path = ROOT / "planet_explorer" / folder / "viewer" / viewer
        text = path.read_text(encoding="utf-8")
        updated, rewrote = gas_apply(text, block, display)
        if updated == text:
            print(f"  {folder:8s} unchanged")
            continue
        if rewrote:
            print(f"  {folder:8s} + {', '.join(rewrote)}")
        stale.append(folder)
        if not check:
            path.write_text(updated, encoding="utf-8")
        print(f"  {folder:8s} {'STALE' if check else 'ported'}")
    if check and stale:
        print(f"drawing tools out of date on: {', '.join(stale)}")
        return 1
    print("uniform" if not stale else f"ported {len(stale)}")
    return 0


