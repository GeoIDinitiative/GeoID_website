def rewrite(text: str, folder: str) -> tuple[str, list[str]]:
    """Apply every REWRITE, reporting which ones this viewer still needed."""
    changed = []
    for old, new, why in REWRITES:
        if new in text:
            continue                      # already ported; a re-run is a no-op
        if old not in text:
            raise SystemExit(f"{folder}: cannot find the anchor for {why}")
        text = text.replace(old, new, 1)
        changed.append(why)
    return text, changed


def earth_block() -> str:
    """The drawing apparatus, lifted verbatim from the Earth viewer."""
    src = EARTH.read_text(encoding="utf-8")
    start = src.index(BLOCK_START)
    end = src.index(BLOCK_END) + len(BLOCK_END)
    return src[start:end]


def render(block: str, group: str, radius_const: str) -> str:
    """The same code, speaking this body's own frame and units."""
    out = block
    # `lonDelta` is already a local in these files; a hoisted function
    # declaration beside a const of that name is a SyntaxError, and one
    # that only bites the world whose file happens to have both.
    out = re.sub(r"\blonDelta\b", "studyLonDelta", out)
    # A kilometre is not a degree anywhere except Earth.
    out = out.replace("111.32", "DRAW_KM_PER_DEG")
    if group != "marsGroup":
        out = re.sub(r"\bmarsGroup\b", group, out)
    header = (
        f"      {OPEN_MARK}\n"
        "      // Edit earth-viewer.js and re-run that script; a hand edit here\n"
        "      // is overwritten, and worse, silently diverges until it is.\n"
        f"      const DRAW_KM_PER_DEG = (2 * Math.PI * {radius_const}) / 360;\n"
    )
    return header + out + f"      {CLOSE_MARK}\n"


def apply(text: str, rendered: str) -> str:
    """Insert the block, or replace the one already there."""
    if OPEN_MARK in text:
        pattern = re.compile(
            r"[ \t]*" + re.escape(OPEN_MARK) + r".*?" + re.escape(CLOSE_MARK) + r"\n",
            re.DOTALL,
        )
        return pattern.sub(rendered, text, count=1)
    if text.count(ANCHOR) != 1:
        raise SystemExit(f"anchor not found exactly once ({text.count(ANCHOR)})")
    return text.replace(ANCHOR, ANCHOR + "\n" + rendered, 1)



