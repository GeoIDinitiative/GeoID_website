#!/usr/bin/env python3
"""Carry the Earth viewer's drawing gestures to the rocky planet viewers.

The press-drag box, the eight visible handles, the live size chip, the
hover cursors and the Escape cancel were written once, in earth-viewer.js.
Every planet viewer is a self-contained COPY of the viewer — there is no
shared module they could import, and `stamp.py` deliberately does not sweep
`planet_explorer/**/*.js` (those files carry epoch-second stamps from
another tooling convention, and an 8-digit rewrite mangles them). So the
choice is five hand-maintained copies or one generator, and this file is
the generator: the copies are marked, so re-running replaces them.

**Edit earth-viewer.js and re-run this. Never edit a generated block.**
That is the lesson the polygon-area formula cost — the same arithmetic
written out in ten places, corrected in one.

Three things are per-body and are rewritten here:

  * the scene group that carries the tilt and spin (`marsGroup` on Earth,
    Mars and the Moon; each of the other worlds has its own),
  * the kilometres in a degree — 111.32 is Earth's and nobody else's, so
    it comes off each viewer's own mean-radius constant,
  * `lonDelta`, which already means something else in these files.

Run:  python3 GeoID_GIS/services/port-draw-tools.py [--check]
"""

