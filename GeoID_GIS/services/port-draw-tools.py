def gas_apply(text: str, block: str, display: str) -> tuple[str, list[str]]:
    changed = []
    prelude = (GAS_PRELUDE.replace("__OPEN__", GAS_OPEN).replace("__CLOSE__", GAS_CLOSE))
    rendered = render(block, "marsGroup", "MARS_MEAN_RADIUS_KM")
    combined = prelude + rendered
    if GAS_OPEN in text:
        pattern = re.compile(r"[ \t]*" + re.escape(GAS_OPEN) + r".*?" + re.escape(CLOSE_MARK) + r"\n", re.DOTALL)
        text = pattern.sub(lambda _m: combined, text, count=1)
    else:
        if text.count(GAS_ANCHOR) != 1:
            raise SystemExit(f"{display}: gas anchor found {text.count(GAS_ANCHOR)} times")
        text = text.replace(GAS_ANCHOR, GAS_ANCHOR + "\n" + combined, 1)
    if GAS_SEAM_MARK in text:
        text = re.sub(r"[ ]*// ── Study areas, published.*?// ── end study areas ──\n", "", text, flags=re.S)
    if text.count(GAS_SEAM_ANCHOR) != 1:
        raise SystemExit(f"{display}: seam anchor found {text.count(GAS_SEAM_ANCHOR)} times")
    text = text.replace(GAS_SEAM_ANCHOR, GAS_SEAM_ANCHOR + GAS_SEAM, 1)
    for old, new, why in GAS_REWRITES:
        if new in text:
            continue
        if text.count(old) != 1:
            raise SystemExit(f"{display}: cannot find the anchor for {why}")
        text = text.replace(old, new, 1)
        changed.append(why)
    # The rocky measure-furniture rewrites are NOT applied here: their
    # replacements name locals (surfaceAnchor, markerEmbedFactor, inMoonViewer)
    # this lineage does not have, and would throw on the first vertex. The same
    # three decisions are written in this lineage's own terms instead.
    for old, new, why in GAS_FURNITURE:
        if new in text:
            continue
        if text.count(old) != 1:
            raise SystemExit(f"{display}: cannot find the anchor for {why}")
        text = text.replace(old, new, 1)
        changed.append(why)
    return text, changed


