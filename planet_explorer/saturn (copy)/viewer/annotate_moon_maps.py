# ── helpers ───────────────────────────────────────────────────────────────────

def latlon_to_xy(lat, lon, W, H):
    x = (lon % 360) / 360.0 * W
    y = (90.0 - lat) / 180.0 * H
    return x, y


def avg_brightness(img):
    thumb = img.convert("L").resize((128, 64), Image.LANCZOS)
    return sum(thumb.getdata()) / (128 * 64)


def load_font(size):
    """Load a monospace/sans font at the given pixel size, fall back to default."""
    candidates = [
        "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
        "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf",
        "/usr/share/fonts/truetype/freefont/FreeSansBold.ttf",
        "/System/Library/Fonts/Helvetica.ttc",
    ]
    for path in candidates:
        if os.path.exists(path):
            return ImageFont.truetype(path, size)
    return ImageFont.load_default()


def text_with_bg(draw, xy, text, font, fg, bg=(0, 0, 0, 180), pad=4):
    """Draw text with a filled background rectangle for legibility."""
    x, y = xy
    bbox = draw.textbbox((x, y), text, font=font)
    draw.rectangle(
        (bbox[0] - pad, bbox[1] - pad, bbox[2] + pad, bbox[3] + pad),
        fill=bg,
    )
    draw.text((x, y), text, font=font, fill=fg)


def draw_grid(draw, W, H, bright, font_axis, font_small):
    """
    Solid lat/lon grid at 30° spacing.
    - Grid lines: white (dark image) or dark-grey (bright image), semi-transparent.
    - Axis labels pinned to the LEFT edge (latitude) and TOP edge (longitude).
    - Equator and prime-meridian are drawn thicker.
    """
    line_w   = max(1, W // 1400)
    thick_w  = max(2, line_w * 3)

    fg  = (255, 255, 255, 240) if bright < 140 else (20, 20, 20, 240)
    gl  = (255, 255, 255, 100) if bright < 140 else (30, 30, 30, 90)

    LON_STEP, LAT_STEP = 30, 30

    # ── longitude lines (vertical) ──────────────────────────────────────────
    for lon in range(0, 360 + 1, LON_STEP):
        x = int(lon / 360.0 * W)
        w = thick_w if lon == 0 else line_w
        draw.line([(x, 0), (x, H)], fill=gl, width=w)
        label = f"{lon}°E"
        bbox = draw.textbbox((0, 0), label, font=font_axis)
        tw = bbox[2] - bbox[0]
        lx = x - tw // 2
        text_with_bg(draw, (lx, 6), label, font_axis, fg)

    # ── latitude lines (horizontal) ─────────────────────────────────────────
    for lat in range(90, -91, -LAT_STEP):
        y = int((90.0 - lat) / 180.0 * H)
        w = thick_w if lat == 0 else line_w
        draw.line([(0, y), (W, y)], fill=gl, width=w)
        # label along the left edge
        label = f"{lat:+d}°"
        bbox = draw.textbbox((0, 0), label, font=font_axis)
        th = bbox[3] - bbox[1]
        ly = y - th // 2
        text_with_bg(draw, (6, ly), label, font_axis, fg)


def draw_features(draw, features, W, H, bright, font_label, moon_name=""):
    """Cross-hair dot + labelled coord for every feature."""
    dot_r = max(6, W // 200)
    ring  = max(2, dot_r // 3)

    dot_col  = (255, 70, 30, 255)
    ring_col = (255, 255, 255, 220)
    txt_col  = (255, 240, 200, 255)
    bg_col   = (0, 0, 0, 175)

    for f in features:
        x, y = latlon_to_xy(f["lat"], f["lon"], W, H)
        arm = dot_r * 3

        # cross-hair
        draw.line([(x - arm, y), (x + arm, y)], fill=ring_col, width=ring)
        draw.line([(x, y - arm), (x, y + arm)], fill=ring_col, width=ring)
        draw.line([(x - arm, y), (x + arm, y)], fill=dot_col,  width=max(1, ring - 1))
        draw.line([(x, y - arm), (x, y + arm)], fill=dot_col,  width=max(1, ring - 1))

        # outer white ring
        draw.ellipse(
            [(x - dot_r - ring, y - dot_r - ring),
             (x + dot_r + ring, y + dot_r + ring)],
            outline=ring_col, width=ring,
        )
        # filled dot
        draw.ellipse(
            [(x - dot_r, y - dot_r), (x + dot_r, y + dot_r)],
            fill=dot_col,
        )

        if moon_name in WEST_POSITIVE_TEXTURE:
            lon_w = f['lon'] % 360
        elif moon_name in CENTERED_TEXTURE:
            lon_w = (540 - f['lon']) % 360
        else:
            lon_w = (360 - f['lon']) % 360
        label = f"{f['name']}\n{f['lat']:+.1f}°,  {lon_w:.1f}°W"
        lx = x + dot_r + ring + 4
        ly = y - dot_r
        text_with_bg(draw, (lx, ly), label, font_label, txt_col, bg_col, pad=5)


